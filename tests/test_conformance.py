class TestCountedClaims:
    def test_the_readme_page_count_matches_the_manual(self) -> None:
        pypdf = pytest.importorskip("pypdf")
        manual = ROOT / "docs" / "Cacophony-Manual.pdf"
        if not manual.is_file():
            pytest.skip("no built manual")

        pages = len(pypdf.PdfReader(str(manual)).pages)
        readme = (ROOT / "README.md").read_text(encoding="utf-8")
        claimed = re.search(r"<!-- claim:pages -->([\d,]+)<!-- /claim -->", readme)
        assert claimed, "README no longer marks its page count"
        assert int(claimed.group(1).replace(",", "")) == pages

    def test_the_manuals_test_count_is_marked(self) -> None:
        """Marked rather than correct: the count changes with this very file."""
        source = (ROOT / "docs" / "manual" / "src" / "12-operating.html").read_text(
            encoding="utf-8"
        )
        assert re.search(r"<!-- claim:tests -->[\d,]+<!-- /claim -->", source)


class TestTheEstimateNamesTheUnitsTheDesignAsks:
    """Section 69 lists four units. Three are estimated; one is refused.

    LLM tokens, output storage and memory are produced. GPU generation time is
    not, and the refusal is recorded in the conformance matrix rather than
    answered with a number nobody could stand behind: it depends on how long a
    step takes on the provider's hardware, and no adapter reports that.
    """

    SCHEMA = {
        "ticket": {
            "count": 1_000,
            "fields": {
                "id": {"type": "integer", "generator": "sequence"},
                "summary": {
                    "type": "text",
                    "semantic": "a one-line summary",
                    "generator": "llm",
                    "on_unavailable": "placeholder",
                    "constraints": {"max_length": 400},
                },
            },
        }
    }

    def _estimate(self, schema=None):
        from helpers import compile_from

        compiled = compile_from(schema or self.SCHEMA)
        assert compiled.plan is not None
        return compiled.plan.estimate

    def test_tokens_come_from_the_declared_length(self) -> None:
        """400 characters is about a hundred tokens, a thousand times over."""
        estimate = self._estimate()
        assert estimate.llm_calls == 1_000
        assert estimate.llm_tokens == pytest.approx(100_000, rel=0.01)

    def test_an_explicit_max_tokens_wins(self) -> None:
        import copy

        schema = copy.deepcopy(self.SCHEMA)
        schema["ticket"]["fields"]["summary"]["max_tokens"] = 32
        assert self._estimate(schema).llm_tokens == 32_000

    def test_a_field_with_no_model_needs_no_tokens(self) -> None:
        schema = {
            "e": {"count": 500, "fields": {"n": {"type": "integer", "generator": "sequence"}}}
        }
        assert self._estimate(schema).llm_tokens == 0

    def test_memory_does_not_grow_with_the_dataset(self) -> None:
        """Section 31's claim, stated as an estimate rather than a hope."""
        import copy

        small = self._estimate()
        larger = copy.deepcopy(self.SCHEMA)
        larger["ticket"]["count"] = 10_000_000
        assert self._estimate(larger).peak_memory_bytes == small.peak_memory_bytes
        assert self._estimate(larger).estimated_bytes > small.estimated_bytes

    def test_the_plan_prints_both(self) -> None:
        from typer.testing import CliRunner

        from cacophony.cli.main import app

        result = CliRunner().invoke(app, ["plan", str(ROOT / "templates" / "helpdesk.yaml")])
        assert result.exit_code == 0, result.stdout
        assert "tokens" in result.stdout
        assert "memory" in result.stdout
