"""The claims this repository makes about itself (design document section 112).

Every number in these documents that went stale did so because somebody typed
it: README said a 165-page manual when it was 173, and the manual said 1,560
tests when there were more than 1,600. Neither was untrue when it was written,
and nothing in the suite noticed.

So the counted claims are measured and written between markers, the conformance
matrix is data rather than prose, and these tests fail when either drifts.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
TOOL = ROOT / "tools" / "conformance.py"

sys.path.insert(0, str(ROOT / "tools"))


@pytest.fixture(scope="module")
def matrix():
    import conformance

    return conformance.load_matrix()


class TestTheMatrixCoversTheDocument:
    def test_every_section_appears_exactly_once(self, matrix) -> None:
        """The check that makes the matrix worth reading."""
        import conformance

        titles = conformance.section_titles()
        listed = [row["section"] for row in matrix]
        assert sorted(listed) == sorted(titles)
        assert len(listed) == len(set(listed))

    def test_the_titles_come_from_the_document(self, matrix) -> None:
        """So a renamed section cannot leave a stale row behind."""
        import conformance

        titles = conformance.section_titles()
        for row in matrix:
            assert row["title"] == titles[row["section"]]

    def test_every_state_is_one_of_the_four(self, matrix) -> None:
        import conformance

        for row in matrix:
            assert row["state"] in conformance.STATES

    def test_anything_less_than_built_explains_itself(self, matrix) -> None:
        """A bare "partial" is a claim with no content."""
        for row in matrix:
            if row["state"] != "implemented":
                assert row.get("note"), f"section {row['section']} is {row['state']} with no note"

    def test_every_refusal_has_a_reason(self, matrix) -> None:
        """Refusing something the design asks for is a position, not a shrug."""
        for row in matrix:
            for refusal in row.get("refuses") or []:
                assert refusal.get("item")
                assert len(refusal.get("why", "")) > 80, f"§{row['section']}: thin reasoning"

    def test_the_known_refusals_are_recorded(self, matrix) -> None:
        """The four decisions taken against the document, by section."""
        refused = {
            row["section"]: [item["item"] for item in row.get("refuses") or []]
            for row in matrix
            if row.get("refuses")
        }
        assert "script" in refused[8][0]
        assert "embedding" in refused[59][0]
        assert "semantic" in refused[67][0]
        assert "GPU" in refused[69][0]


